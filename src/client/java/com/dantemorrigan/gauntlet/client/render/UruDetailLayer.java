package com.dantemorrigan.gauntlet.client.render;

import com.dantemorrigan.gauntlet.InfinityGauntlet;
import com.dantemorrigan.gauntlet.ModItems;
import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.math.Axis;
import net.minecraft.client.Minecraft;
import net.minecraft.client.model.HumanoidModel;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.renderer.SubmitNodeCollector;
import net.minecraft.client.renderer.entity.RenderLayerParent;
import net.minecraft.client.renderer.entity.layers.RenderLayer;
import net.minecraft.client.renderer.entity.state.HumanoidRenderState;
import net.minecraft.client.renderer.item.ItemStackRenderState;
import net.minecraft.client.renderer.texture.OverlayTexture;
import net.minecraft.core.component.DataComponents;
import net.minecraft.world.item.ItemDisplayContext;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.Items;

import java.util.HashMap;
import java.util.Map;

/**
 * The 3D parts of the Armor of Uru on top of the vanilla armor layers: winged helmet with a rune crest, chest gem,
 * belt and tabards, pauldrons and bracers with runes, knee guards and boot cuffs (runes and gem glow). Each set of
 * boxes is an item model (generated by art/source/uru/make_models.py) drawn in the frame of its model part, so it
 * follows every animation of any humanoid model (players, the Steve doll, zombies...).
 */
public class UruDetailLayer<S extends HumanoidRenderState, M extends HumanoidModel<S>> extends RenderLayer<S, M> {
	private static final Map<String, ItemStackRenderState> MODELS = new HashMap<>();

	public UruDetailLayer(RenderLayerParent<S, M> parent) {
		super(parent);
	}

	@Override
	public void submit(PoseStack pose, SubmitNodeCollector collector, int light, S state, float yRot, float xRot) {
		M model = this.getParentModel();
		if (state.headEquipment.is(ModItems.URU_HELMET)) part(pose, collector, light, model.head, "helmet");
		if (state.chestEquipment.is(ModItems.URU_CHESTPLATE)) {
			part(pose, collector, light, model.body, "chest");
			part(pose, collector, light, model.rightArm, "pauldron_right");
			part(pose, collector, light, model.leftArm, "pauldron_left");
		}
		if (state.legsEquipment.is(ModItems.URU_LEGGINGS)) {
			part(pose, collector, light, model.rightLeg, "knee");
			part(pose, collector, light, model.leftLeg, "knee");
		}
		if (state.feetEquipment.is(ModItems.URU_BOOTS)) {
			part(pose, collector, light, model.rightLeg, "boot");
			part(pose, collector, light, model.leftLeg, "boot");
		}
	}

	static void part(PoseStack pose, SubmitNodeCollector collector, int light, ModelPart part, String name) {
		if (!part.visible) return;
		pose.pushPose();
		part.translateAndRotate(pose);
		pose.mulPose(Axis.XP.rotationDegrees(180)); // item models are Y-up, model parts Y-down
		model(name).submit(pose, collector, light, OverlayTexture.NO_OVERLAY, 0);
		pose.popPose();
	}

	private static ItemStackRenderState model(String name) {
		ItemStackRenderState state = MODELS.computeIfAbsent(name, n -> new ItemStackRenderState());
		Minecraft mc = Minecraft.getInstance();
		ItemStack stack = new ItemStack(Items.STICK);
		stack.set(DataComponents.ITEM_MODEL, InfinityGauntlet.id("uru_detail_" + name));
		mc.getItemModelResolver().updateForTopItem(state, stack, ItemDisplayContext.NONE, mc.level, null, 0);
		return state;
	}
}
