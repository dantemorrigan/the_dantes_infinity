package com.dantemorrigan.gauntlet.guide;

import com.dantemorrigan.gauntlet.GauntletConfig;
import com.dantemorrigan.gauntlet.InfinityGauntlet;
import com.dantemorrigan.gauntlet.Stone;
import com.mojang.serialization.Codec;
import net.fabricmc.fabric.api.attachment.v1.AttachmentRegistry;
import net.fabricmc.fabric.api.attachment.v1.AttachmentType;
import net.fabricmc.fabric.api.command.v2.CommandRegistrationCallback;
import net.fabricmc.fabric.api.event.player.UseItemCallback;
import net.fabricmc.fabric.api.networking.v1.ServerPlayConnectionEvents;
import net.minecraft.ChatFormatting;
import net.minecraft.commands.Commands;
import net.minecraft.core.component.DataComponents;
import net.minecraft.network.chat.Component;
import net.minecraft.network.chat.MutableComponent;
import net.minecraft.network.chat.contents.TranslatableContents;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.server.network.Filterable;
import net.minecraft.world.InteractionResult;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.Items;
import net.minecraft.world.item.component.WrittenBookContent;

import java.util.ArrayList;
import java.util.List;

/**
 * The in-game field guide. Every page is a translatable component ({@code guide.infinity_gauntlet.pN.K} segments), so one
 * book reads in whichever language the client uses (including the mod's own language switch). The page texts are
 * generated by {@code scripts/gen_guide.py}.
 */
public final class GuideBook {
	/** Number of pages in the generated guide. */
	public static final int PAGE_COUNT = GuidePages.STYLES.length;

	private static final List<Stone> STONE_CHAPTERS = List.of(
			Stone.POWER, Stone.SPACE, Stone.REALITY, Stone.TIME, Stone.MIND, Stone.SOUL);

	/** Set once a player has received the book, so it is handed out only on their first join. */
	private static final AttachmentType<Boolean> GIVEN = AttachmentRegistry.<Boolean>builder()
			.persistent(Codec.BOOL)
			.copyOnDeath()
			.buildAndRegister(InfinityGauntlet.id("guide_given"));

	public static ItemStack create() {
		ItemStack book = new ItemStack(Items.WRITTEN_BOOK);
		book.set(DataComponents.WRITTEN_BOOK_CONTENT,
				new WrittenBookContent(Filterable.passThrough("Infinity Gauntlet"), "Infinity Gauntlet", 0, pages(), true));
		book.set(DataComponents.CUSTOM_NAME, Component.translatable("guide.infinity_gauntlet.title")
				.withStyle(s -> s.withItalic(false).withColor(ChatFormatting.LIGHT_PURPLE).withBold(true)));
		return book;
	}

	private static List<Filterable<Component>> pages() {
		List<Filterable<Component>> pages = new ArrayList<>(PAGE_COUNT);
		for (int i = 1; i <= PAGE_COUNT; i++) pages.add(Filterable.passThrough(page(i)));
		return pages;
	}

	private static void refresh(ItemStack stack) {
		WrittenBookContent book = stack.get(DataComponents.WRITTEN_BOOK_CONTENT);
		if (book == null || book.pages().isEmpty() || book.pages().size() >= PAGE_COUNT
				|| !book.author().equals("Infinity Gauntlet")) return;
		// The page key identifies old field guides even if the owner renamed the item.
		if (book.pages().getFirst().raw().getSiblings().stream().anyMatch(part ->
				part.getContents() instanceof TranslatableContents text && text.getKey().equals("guide.infinity_gauntlet.p1.1"))) {
			stack.set(DataComponents.WRITTEN_BOOK_CONTENT, book.withReplacedPages(pages()));
		}
	}

	/** One page: styled translatable segments (legacy section codes render badly inside books). */
	private static Component page(int number) {
		String styles = GuidePages.STYLES[number - 1];
		MutableComponent page = Component.empty();
		for (int j = 0; j < styles.length(); j++) {
			MutableComponent part = Component.translatable("guide.infinity_gauntlet.p" + number + "." + (j + 1));
			Stone stone = stoneForSegment(number, j + 1);
			if (stone != null) {
				page.append(part.withStyle(style -> style.withColor(bookColor(stone)).withBold(true)));
				continue;
			}
			page.append(switch (styles.charAt(j)) {
				case 'H' -> part.withStyle(ChatFormatting.DARK_PURPLE, ChatFormatting.BOLD);
				case 'B' -> part.withStyle(ChatFormatting.BLACK, ChatFormatting.BOLD);
				case 'G' -> part.withStyle(ChatFormatting.DARK_GRAY);
				default -> part.withStyle(ChatFormatting.BLACK);
			});
		}
		return page;
	}

	private static Stone stoneForSegment(int page, int segment) {
		// Contents labels alternate with page numbers. The hints also include the Soul Stone.
		if (page == 2 && segment >= 6 && segment <= 16 && segment % 2 == 0) {
			return STONE_CHAPTERS.get((segment - 6) / 2);
		}
		if (page == 4 && segment >= 3 && segment <= 13 && segment % 2 == 1) {
			return STONE_CHAPTERS.get((segment - 3) / 2);
		}
		if (page >= 6 && page <= 11 && segment == 1) {
			return STONE_CHAPTERS.get(page - 6);
		}
		return null;
	}

	private static int bookColor(Stone stone) {
		// Keep the lighter stone colors legible on the parchment.
		return switch (stone) {
			case MIND -> 0x896100;
			case SOUL -> 0xA54400;
			case TIME -> 0x007527;
			default -> stone.color;
		};
	}

	public static void give(ServerPlayer player) {
		ItemStack book = create();
		if (!player.getInventory().add(book)) player.drop(book, false);
	}

	public static void init() {
		UseItemCallback.EVENT.register((player, level, hand) -> {
			refresh(player.getItemInHand(hand));
			return InteractionResult.PASS;
		});
		ServerPlayConnectionEvents.JOIN.register((handler, sender, server) -> {
			ServerPlayer player = handler.getPlayer();
			if (!GauntletConfig.get().giveGuideBook || player.hasAttached(GIVEN)) return;
			player.setAttached(GIVEN, true);
			give(player);
		});
		// Anyone can get the book back, no operator rights needed.
		CommandRegistrationCallback.EVENT.register((dispatcher, context, selection) -> dispatcher.register(
				Commands.literal("gauntlet_guide").executes(ctx -> {
					give(ctx.getSource().getPlayerOrException());
					return 1;
				})));
	}

	private GuideBook() {}
}
